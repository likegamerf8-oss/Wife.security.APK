package com.example.adapter

import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow

/**
 * Clearly labeled Test Double / Simulator adapter.
 * Used for reliable, offline end-to-end execution of approval flows,
 * edge cases, and automated verification without requiring physical router hardware.
 */
class TestDoubleSimulatorAdapter : RouterAdapter {

    override val adapterId = "adapter_test_double"
    override val adapterName = "TEST DOUBLE / LOCAL SIMULATOR (Sandbox)"
    override val isTestDouble = true

    private var accessList = mutableSetOf("B4:CE:F6:12:34:56", "3C:06:30:78:90:AB", "58:D9:C3:FA:BC:DE")
    private var blockedList = mutableSetOf("DE:AD:BE:EF:00:11")

    override suspend fun discoverCapabilities(): IntegrationCapabilities {
        return IntegrationCapabilities(
            readRouterIdentity = CapabilityStatus.SUPPORTED,
            readConnectedDevices = CapabilityStatus.SUPPORTED,
            detectNewAssociations = CapabilityStatus.SUPPORTED,
            preAccessApproval = CapabilityStatus.SUPPORTED,
            postAccessRevocation = CapabilityStatus.SUPPORTED,
            guestAccessControl = CapabilityStatus.SUPPORTED,
            bandwidthThrottling = CapabilityStatus.SUPPORTED
        )
    }

    override suspend fun getRouterIdentity(): Result<RouterIdentity> {
        return Result.success(
            RouterIdentity(
                manufacturer = "Simulator Lab",
                model = "Virtual Security Gateway v2",
                hardwareRevision = "SIM-HW-01",
                serialNumber = "SIM-BD-TEST-999",
                macAddress = "02:00:00:00:00:01",
                uptimeSeconds = 172800L
            )
        )
    }

    override suspend fun getFirmwareInformation(): Result<FirmwareInfo> {
        return Result.success(
            FirmwareInfo(
                version = "Simulator Core 2.5-verified",
                kernelVersion = "Virtual-Linux 6.1",
                buildDate = "2026-03-01",
                patchLevel = "Test-Rig Pass"
            )
        )
    }

    override suspend fun listConnectedDevices(): Result<List<RawRouterDevice>> {
        return Result.success(
            listOf(
                RawRouterDevice(
                    macAddress = "B4:CE:F6:12:34:56",
                    ipAddress = "192.168.1.101",
                    hostname = "Arman-Pixel8-Pro",
                    signalDbm = -50,
                    rxRateMbps = 450f,
                    txRateMbps = 450f,
                    isAssociated = true,
                    isAuthorized = true,
                    connectionType = "5GHz"
                ),
                RawRouterDevice(
                    macAddress = "2A:B5:1C:DF:88:99",
                    ipAddress = "192.168.1.155",
                    hostname = "Galaxy-A54-Guest",
                    signalDbm = -65,
                    rxRateMbps = 72f,
                    txRateMbps = 72f,
                    isAssociated = true,
                    isAuthorized = accessList.contains("2A:B5:1C:DF:88:99"),
                    connectionType = "2.4GHz"
                )
            )
        )
    }

    override suspend fun observeConnectionEvents(): Flow<RawRouterEvent> = flow {
        emit(
            RawRouterEvent(
                eventType = "NEW_STATION",
                macAddress = "2A:B5:1C:DF:88:99",
                timestamp = System.currentTimeMillis(),
                description = "Simulator event: Station probe detected"
            )
        )
    }

    override suspend fun approveDevice(mac: String, ip: String): Result<Boolean> {
        accessList.add(mac)
        blockedList.remove(mac)
        return Result.success(true)
    }

    override suspend fun denyDevice(mac: String): Result<Boolean> {
        accessList.remove(mac)
        blockedList.add(mac)
        return Result.success(true)
    }

    override suspend fun revokeDeviceAccess(mac: String): Result<Boolean> {
        accessList.remove(mac)
        blockedList.add(mac)
        return Result.success(true)
    }

    override suspend fun getIntegrationHealth(): IntegrationHealth {
        return IntegrationHealth(
            isReachable = true,
            latencyMs = 2L,
            lastSyncTimestamp = System.currentTimeMillis(),
            apiStatusCode = 200
        )
    }

    override suspend fun testReadOnlyConnection(): Result<ConnectionTestResult> {
        return Result.success(
            ConnectionTestResult(
                success = true,
                httpStatus = 200,
                latencyMs = 2L,
                verifiedCapabilitiesCount = 7,
                warnings = listOf("[SIMULATED DOUBLE]: Responses generated by in-memory sandbox for offline test verification."),
                message = "Test double initialized successfully."
            )
        )
    }
}
